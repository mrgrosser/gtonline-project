"""Private raw round-event receipts, NOT completed-round/statistical projection.

22v2 flags0 is live-captured; flags2 and31v1 remain schema-derived.
30v0 end shape is captured, but end does not prove a finished/scored round.
No wallet/refund route and no network ACK is generated by this module.
"""
from dataclasses import dataclass,field
import hashlib,os,secrets,struct
from pathlib import Path

@dataclass(frozen=True)
class RoundEvent:
    message:int
    version:int
    session:int
    fields:dict=field(repr=False)
    raw:bytes=field(repr=False)

#22v2 flags0 is witnessed in roundcapture003; flags2 and31 remain offline only.
#30 flags2 is observed on aborted lifecycle. Never infer completion from it.
_LENGTHS={b'\x40\x16':40,b'\x42\x16':40,b'\x02\x1e':31,b'\x22\x1f':474}

def inspect_round_events(raw,identity):
    if type(raw) is not bytes or type(identity) is not bytes or len(identity)!=20:
        raise ValueError('Byte payload and opaque pinned identity required')
    if not raw:raise ValueError('Empty round event bundle')
    events=[];offset=0
    while offset<len(raw):
        header=raw[offset:offset+2];length=_LENGTHS.get(header)
        if length is None or offset+length>len(raw):raise ValueError('Unsupported or truncated round event')
        event_raw=raw[offset:offset+length];data=event_raw[2:];mid=header[1];version=header[0]>>5
        if mid==22:
            index,score,great,points,hole,status=struct.unpack('>HhIIBB',data[:14])
            player=data[14:34];session=int.from_bytes(data[34:38],'big')
            fields=dict(PLAYER_INDEX=index,SCORE=score,GREAT_SHOT_POINTS=great,GOLDEN_T_POINTS=points,CURRENT_HOLE=hole,PLAYER_STATUS=status)
        elif mid==30:
            session,end=struct.unpack('>II',data[:8]);player=data[8:28]
            fields=dict(END_TIME_GMT=end,PLAYER_NUM=int.from_bytes(data[28:29],'big',signed=True))
        else:
            session,course=struct.unpack('>II',data[:8]);player=data[8:28]
            fields=dict(COURSE_ID=course,SESSION_DATA=data[28:])
            if len(fields['SESSION_DATA'])!=444:raise ValueError('Exact v1 session data required')
        if not secrets.compare_digest(player,identity):raise ValueError('Player outside pinned round scope')
        events.append(RoundEvent(mid,version,session,fields,event_raw));offset+=length
    if len({e.session for e in events})!=1:raise ValueError('Mixed sessions in round event bundle')
    return tuple(events)

class DurableRoundEventJournal:
    """Immutable content-addressed bundle receipt; preserves repeats/updates honestly.

    Same bytes replay idempotently; changed reports are new evidence, not silently
    overwritten. End markers are never promoted to completed rounds. No importer,
    player statistics, game wallet, or equipment state is modified.
    """
    def __init__(self,directory):
        self.directory=Path(directory);self.directory.mkdir(mode=0o700,parents=True,exist_ok=True)
        if self.directory.is_symlink() or self.directory.stat().st_mode&0o077:
            raise ValueError('Private non-symlink event directory required')
    def record(self,raw,identity):
        events=inspect_round_events(raw,identity)
        digest=hashlib.sha256(raw).hexdigest();path=self.directory/(digest+'.bin')
        try:fd=os.open(path,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,0o600)
        except FileExistsError:
            fd=os.open(path,os.O_RDONLY|os.O_NOFOLLOW)
            with os.fdopen(fd,'rb') as stream:
                if stream.read()!=raw:raise ValueError('Conflicting immutable receipt')
                os.fsync(stream.fileno())
        else:
            with os.fdopen(fd,'wb') as stream:stream.write(raw);stream.flush();os.fsync(stream.fileno())
        fd=os.open(self.directory,os.O_RDONLY|os.O_DIRECTORY)
        try:os.fsync(fd)
        finally:os.close(fd)
        return {'events_received':len(events),'receipt_sha256':digest,'completed_round':False}
